// Builds public/icons/sprite.svg from @phosphor-icons/core.
//
// Why a committed sprite: this project has no build step, so there is nothing to transform an icon
// package at deploy time, and Section 3.C of the design skill rules out hand-drawn SVG paths. A
// sprite generated from a real library and committed is the same pattern already used for the PWA
// PNGs (scripts/build-icons.mjs) and the modulepreload lists (scripts/build-preloads.mjs): generate
// it, commit the output, and let `npm run check` fail if it drifts.
//
//   node scripts/build-icon-sprite.mjs           # rewrite the sprite
//   node scripts/build-icon-sprite.mjs --check   # fail if it is stale
//
// Only the icons listed below are included, so the sprite stays a few KB rather than shipping all
// ~1,500 of Phosphor's glyphs.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const SRC = 'node_modules/@phosphor-icons/core/assets';
const OUT = 'public/icons/sprite.svg';

