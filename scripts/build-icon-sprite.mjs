/** Pulls the drawing out of a Phosphor file and re-wraps it as a <symbol>. */
function symbolFor(id, weight, name) {
  // Phosphor suffixes every non-regular weight in the filename: heart.svg vs heart-fill.svg.
  const file_name = weight === 'regular' ? name : `${name}-${weight}`;
  const path = `${SRC}/${weight}/${file_name}.svg`;
  if (!existsSync(path)) throw new Error(`missing icon: ${path}`);
  const file = readFileSync(path, 'utf8');
  const viewBox = (file.match(/viewBox="([^"]+)"/) || [])[1] || '0 0 256 256';
  const body = file
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>/, '')
    .replace(/<rect[^>]*width="256"[^>]*height="256"[^>]*fill="none"[^>]*\/>/g, '') // Phosphor's bounding rect
    .trim();
  // currentColor so one sprite serves both themes and every accent.
  return `  <symbol id="i-${id}" viewBox="${viewBox}" fill="currentColor">${body}</symbol>`;
}

const symbols = Object.entries(ICONS).map(([id, [weight, name]]) => symbolFor(id, weight, name));
const sprite = [
  '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">',
  '  <!-- Generated by scripts/build-icon-sprite.mjs from @phosphor-icons/core. Do not edit by hand. -->',
  ...symbols,
  '</svg>',
  '',
].join('\n');

mkdirSync('public/icons', { recursive: true });
const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';

if (process.argv.includes('--check')) {
  if (current !== sprite) {
    console.error(`${OUT} is stale — run \`node scripts/build-icon-sprite.mjs\``);
    process.exit(1);
  }
  console.log(`${OUT}: up to date (${symbols.length} icons)`);
} else {
  writeFileSync(OUT, sprite);
  console.log(`wrote ${OUT} (${symbols.length} icons, ${Math.round(sprite.length / 1024)}KB)`);
}
