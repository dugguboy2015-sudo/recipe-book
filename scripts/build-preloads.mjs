// Generates the <link rel="modulepreload"> block in each page's <head>.
//
// Why this exists: there is no build step (a standing constraint), so the browser discovers this
// app's modules by reading one, parsing it, and fetching what it imports — wave after wave. The
// recipes page is 35 modules at an import depth of 7, behind a dynamic import in main.js, so a
// cold phone pays eight sequential round trips before anything renders. A preload list is the
// no-bundler fix: the browser starts fetching the whole graph immediately, in parallel.
//
//   node scripts/build-preloads.mjs            # rewrite the block in every page
//   node scripts/build-preloads.mjs --check    # fail if any page's block is stale (used by npm run check)
//
// A hand-maintained list would go stale the first time someone added an import, which is exactly
// the failure the service worker's precache list was rejected for in M4 — so it is generated, and
// `npm run check` fails if it drifts.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';

const JS_ROOT = 'public/js';
const START = '  <!-- modulepreload: generated by scripts/build-preloads.mjs — do not edit by hand -->';
const END = '  <!-- /modulepreload -->';

const PAGES = {
  'public/index.html': 'pages/dashboard.js',
  'public/recipes.html': 'pages/recipes.js',
  'public/planner.html': 'pages/planner.js',
  'public/shopping.html': 'pages/shopping.js',
};

/** Static imports only — a dynamic import() is deliberately deferred and must not be preloaded. */
function staticImports(file) {
  const source = readFileSync(file, 'utf8');
  return [...source.matchAll(/^\s*import\s[^'"]*['"]([^'"]+)['"]/gm)]
    .map((match) => match[1])
    .filter((specifier) => specifier.startsWith('.'))
    .map((specifier) => resolve(dirname(file), specifier))
    .filter(existsSync);
}

function reachable(file, found = new Set()) {
  if (found.has(file)) return found;
  found.add(file);
  for (const child of staticImports(file)) reachable(child, found);
  return found;
}

/** The longest chain of imports — the number of sequential round trips without a preload list. */
export function importDepth(file, seen = new Set()) {
  if (seen.has(file)) return 0;
  seen.add(file);
  const children = staticImports(file).map((child) => importDepth(child, new Set(seen)));
  return 1 + Math.max(0, ...children);
}

function preloadsFor(pageEntry) {
  // main.js and the account control load on every page; the page module is dynamically imported by
  // main.js, so without this the browser cannot even see it until main.js has run.
  const roots = [
    resolve(JS_ROOT, 'main.js'),
    resolve(JS_ROOT, 'components/account.js'),
    resolve(JS_ROOT, pageEntry),
  ];
  const all = new Set();
  for (const root of roots) reachable(root, all);
  all.delete(resolve(JS_ROOT, 'main.js')); // already requested by the <script type="module">
  return [...all]
    .map((file) => 'js/' + relative(JS_ROOT, file).split('\\').join('/'))
    .sort();
}

function blockFor(pageEntry) {
  const links = preloadsFor(pageEntry).map((href) => `  <link rel="modulepreload" href="${href}" />`);
  return [START, ...links, END].join('\n');
}

let stale = 0;
for (const [page, entry] of Object.entries(PAGES)) {
  const html = readFileSync(page, 'utf8');
  const newline = html.includes('\r\n') ? '\r\n' : '\n';
  const block = blockFor(entry).split('\n').join(newline);

  const startAt = html.indexOf(START);
  const endAt = html.indexOf(END);
  let updated;
  if (startAt >= 0 && endAt > startAt) {
    updated = html.slice(0, startAt) + block + html.slice(endAt + END.length);
  } else {
    // First run: insert just above the module script tag's closing </head>.
    const headClose = html.indexOf('</head>');
    if (headClose < 0) throw new Error(`${page}: no </head>`);
    updated = html.slice(0, headClose) + block + newline + html.slice(headClose);
  }

  if (updated === html) {
    console.log(`${page}: up to date (${preloadsFor(entry).length} modules)`);
    continue;
  }
  if (process.argv.includes('--check')) {
    console.error(`${page}: modulepreload block is stale — run \`node scripts/build-preloads.mjs\``);
    stale += 1;
  } else {
    writeFileSync(page, updated);
    console.log(`${page}: wrote ${preloadsFor(entry).length} preloads (import depth ${importDepth(resolve(JS_ROOT, entry))})`);
  }
}

if (stale) process.exit(1);
