import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { ING } from './data/ingredient-dictionary.mjs';

function sqlStr(v) {
  if (v === null || v === undefined) return 'null';
  return `'${String(v).replace(/'/g, "''")}'`;
}
function sqlBool(v) {
  return v ? 'true' : 'false';
}
function sqlNum(v) {
  return v === null || v === undefined ? 'null' : String(v);
}

// --- 010_ingredients_backfill.sql: ingredients, aliases, recipe_ingredients ---
const backfill = JSON.parse(readFileSync('migrations/data/ingredients_backfill.json', 'utf8'));

const ingredientKeys = Object.keys(ING).sort();
const ingredientValues = ingredientKeys.map((key) => {
  const def = ING[key];
  return `  (${sqlStr(key)}, ${sqlStr(def.display_name)}, ${sqlStr(def.category)}, ${sqlBool(def.meat)}, ${sqlBool(def.egg)}, ${sqlBool(def.dairy)}, ${sqlBool(def.nuts)}, ${sqlBool(def.gluten)})`;
}).join(',\n');

const aliasRows = [];
for (const key of ingredientKeys) {
  for (const alias of ING[key].aliases) aliasRows.push({ alias, key });
}
aliasRows.sort((a, b) => a.alias.localeCompare(b.alias));
const aliasValues = aliasRows.map((r) => `  (${sqlStr(r.alias)}, (select id from public.ingredients where name = ${sqlStr(r.key)}))`).join(',\n');

const sortedBackfill = [...backfill].sort((a, b) => a.recipe_id - b.recipe_id || a.group_position - b.group_position || a.position - b.position);
const recipeIngredientValues = sortedBackfill.map((r) => {
  return `  (${r.recipe_id}, ${sqlStr(r.group_name)}, ${r.group_position}, ${r.position}, (select id from public.ingredients where name = ${sqlStr(r.ingredient)}), ${sqlNum(r.quantity)}, ${sqlStr(r.unit)}, ${sqlStr(r.preparation)}, ${sqlBool(r.is_optional)}, ${sqlBool(r.scales)}, ${sqlStr(r.original_text)})`;
}).join(',\n');

const migration010 = `-- Phase 3 backfill, generated by scripts/build-backfill-sql.mjs from
-- scripts/data/ingredient-dictionary.mjs and migrations/data/ingredients_backfill.json.
-- Deterministic and sorted: rebuilding from the same source data produces no diff.

insert into public.ingredients (name, display_name, category, contains_meat, contains_egg, contains_dairy, contains_nuts, contains_gluten) values
${ingredientValues}
on conflict (name) do nothing;

insert into public.ingredient_aliases (alias, ingredient_id) values
${aliasValues}
on conflict (alias) do nothing;

insert into public.recipe_ingredients (recipe_id, group_name, group_position, position, ingredient_id, quantity, unit, preparation, is_optional, scales, original_text) values
${recipeIngredientValues};
`;

writeFileSync('migrations/010_ingredients_backfill.sql', migration010);
console.log(`010_ingredients_backfill.sql: ${ingredientKeys.length} ingredients, ${aliasRows.length} aliases, ${sortedBackfill.length} recipe_ingredients rows`);

// --- 011_nutrition_backfill.sql: sugars/saturates/salt, spice_level, nutrition_source, corrections ---
if (existsSync('migrations/data/nutrition_backfill.json')) {
  const nutrition = JSON.parse(readFileSync('migrations/data/nutrition_backfill.json', 'utf8'));
  const sorted = [...nutrition].sort((a, b) => a.recipe_id - b.recipe_id);
  const sets = sorted.map((n) => {
    const corrections = n.corrections || {};
    const correctionSql = Object.entries(corrections).map(([field, [, newVal]]) => `${field} = ${sqlNum(newVal)}`).join(', ');
    const parts = [
      `sugars_g = ${sqlNum(n.sugars_g)}`,
      `saturates_g = ${sqlNum(n.saturates_g)}`,
      `salt_g = ${sqlNum(n.salt_g)}`,
      `spice_level = ${sqlNum(n.spice_level)}`,
      `nutrition_source = 'backfill_estimate'`,
      ...(correctionSql ? [correctionSql] : []),
    ];
    return `update public.recipes set ${parts.join(', ')} where id = ${n.recipe_id};`;
  }).join('\n');

  const migration011 = `-- Phase 3 nutrition backfill, generated by scripts/build-backfill-sql.mjs from
-- migrations/data/nutrition_backfill.json. Deterministic and sorted by recipe id.
-- refined_carb_heavy and contains_nuts are set by refresh_recipe_derived() in 012, which also
-- needs recipe_ingredients (010) in place — that's why is_protein_smart can't be assessed until
-- after 012 runs, even though sugars_g lands here in 011.

${sets}
`;
  writeFileSync('migrations/011_nutrition_backfill.sql', migration011);
  console.log(`011_nutrition_backfill.sql: ${sorted.length} recipes updated`);
} else {
  console.log('migrations/data/nutrition_backfill.json not found yet; skipping 011.');
}
